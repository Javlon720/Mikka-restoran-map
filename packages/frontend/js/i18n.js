let currentLang = localStorage.getItem('jdu_lang') || 'en';

function getTranslation(key, replacements = {}) {
  const catalog = translations[currentLang] || translations['en'];
  let text = catalog[key] || translations['en'][key] || key;
  
  for (const [placeholder, value] of Object.entries(replacements)) {
    text = text.replace(`{${placeholder}}`, value);
  }
  return text;
}

function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem('jdu_lang', lang);
    applyTranslations();
  }
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    element.textContent = getTranslation(key);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    const key = element.getAttribute('data-i18n-placeholder');
    element.setAttribute('placeholder', getTranslation(key));
  });
}

// Export for browser global usage
window.i18n = {
  get: getTranslation,
  set: setLanguage,
  current: () => currentLang,
  apply: applyTranslations
};
